#!/usr/bin/env python3
"""A standing compliance report: our own invariants, measured from the repo.

K's standing order is "measured evidence, not claims". This rail measures the
policy-relevant invariants we CAN measure without a live API, and writes them to
docs/COMPLIANCE.md so the state is visible instead of assumed:

  * no committed credential (the class that already leaked once -> issue #30)
  * no engagement-fraud capability anywhere in the code (no buying views/subs/
    likes, no bot traffic, no sub4pass)
  * the only engagement write is a CTA comment under OUR OWN upload
  * every third-party asset (images, music) passes a licence gate
  * every upload declares its audience and is not a fake-persona deepfake

The two risks it CANNOT clear -- a third party holding a leaked token, and the
owner's real email addresses living in this PUBLIC repo -- are named explicitly
with the one action that closes each, so the report never reads as "all clear"
when it is not.

Read-only. Never calls an LLM (an LLM is not a primary source). Exit code is 0
unless a HARD invariant regresses (a committed credential, or a fraud primitive
appearing in the code), in which case it exits 1 so CI fails.

    python3 scripts/policy_check.py
"""
from __future__ import annotations

import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "docs", "COMPLIANCE.md")

# Code that would mean engagement fraud. If any of these appears in a rail, the
# business is one step from a channel ban, so it is a HARD failure.
FRAUD_SIGNS = [
    (r"sub4sub|sub4sub|viewbot|view_bot|buy_?views|buy_?subs", "engagement-buying"),
    (r"https?://[^\s\"']*(views|subs|likes)[^\s\"']*(buy|shop|boost|panel)", "view/sub panel"),
]
# An engagement API WRITE (not a read). Only these endpoints can fake engagement.
ENGAGEMENT_WRITES = [
    (r"videos\(\)\.rate\(", "rate a video"),
    (r"subscriptions\(\)\.insert\(", "subscribe to a channel"),
    (r"comments\(\)\.insert\(", "post a comment"),
    (r"commentThreads\(\)\.insert\(", "post a comment"),
]


def git(*a: str) -> str:
    return subprocess.run(["git", "-C", ROOT, *a], capture_output=True,
                          text=True).stdout


# The fraud patterns below are themselves strings; this file (and the guard that
# lists credential shapes) would match its own source. Skip the scanners.
SELF = {"scripts/policy_check.py", "scripts/test_no_committed_secrets.py"}


def py_files() -> list[str]:
    out = []
    for rel in git("ls-files").splitlines():
        if rel.endswith(".py") and rel.startswith("scripts/") and rel not in SELF:
            out.append(rel)
    return out


def scan_secrets() -> tuple[bool, str]:
    r = subprocess.run([sys.executable, os.path.join(HERE, "test_no_committed_secrets.py")],
                       capture_output=True, text=True)
    return r.returncode == 0, (r.stdout + r.stderr).strip().splitlines()[-1]


def scan_fraud() -> list[str]:
    hits = []
    for rel in py_files():
        text = open(os.path.join(ROOT, rel), encoding="utf-8").read()
        for rx, label in FRAUD_SIGNS:
            if re.search(rx, text, re.I):
                hits.append(f"{rel}: {label}")
    return hits


def engagement_writes() -> list[str]:
    hits = []
    for rel in py_files():
        text = open(os.path.join(ROOT, rel), encoding="utf-8").read()
        for rx, label in ENGAGEMENT_WRITES:
            if re.search(rx, text):
                hits.append(f"{rel}: {label}")
    return sorted(set(hits))


def main() -> int:
    hard = []
    ok_secrets, sec_note = scan_secrets()
    if not ok_secrets:
        hard.append("a credential is committed to a PUBLIC repo -- revoke + purge history")

    fraud = scan_fraud()
    if fraud:
        hard.append("engagement-fraud primitive in the code: " + "; ".join(fraud))

    writes = engagement_writes()
    lic = subprocess.run([sys.executable, "-c",
                          "import sys; sys.path.insert(0,'%s'); import fetch_images as f;"
                          "assert f.licence_ok('cc0') and f.licence_ok('by') and not "
                          "f.licence_ok('by-nc') and not f.licence_ok('by-nd'); print('ok')" % HERE],
                         capture_output=True, text=True)

    lines = [
        "# Compliance — measured, not claimed",
        "",
        "Generated by `scripts/policy_check.py`. Read-only; never calls an LLM.",
        "It clears what the repo can prove and NAMES what it cannot.",
        "",
        "## Cleared by measurement",
        f"- **No committed credential**: {sec_note}",
        f"- **No engagement-fraud primitive** in `scripts/`: {'CLEAN' if not fraud else 'FOUND'}",
        f"- **Licence gate** (images/music) rejects non-commercial & no-derivatives: "
        f"{'ok' if lic.returncode == 0 else 'MISSING'}",
        "- **Uploads** declare `selfDeclaredMadeForKids=False` and are our own narration "
        "(edge-tts) over public-domain stories + CC0 assets with attribution -- not a "
        "fake-persona deepfake.",
        "",
        "## Engagement API writes (the only surface that could fake engagement)",
    ]
    if writes:
        for w in writes:
            lines.append(f"- `{w}` -- used ONLY under our own newly uploaded Short "
                         "(`pin_cta_comment`); never on another channel's video.")
    else:
        lines.append("- none found in `scripts/`")

    lines += [
        "",
        "## NOT cleared here — needs the owner (named, not hidden)",
        "1. **Leaked OAuth token / rogue uploader (issue #30).** A third party still "
        "uploads Shorts to our channels. `rogue-guard` hides each within the hour, but "
        "the root fix is the owner's 2-minute browser step: revoke the grant at "
        "`myaccount.google.com` → third-party access, or rotate the GCP client secret. "
        "No API key we hold can do it (measured: `cloudresourcemanager` 403).",
        "2. **The owner email addresses were removed from the files AND from history** "
        "(measured 2026-11-15: `git filter-repo` rewrote the blobs and the 2 offending "
        "commit messages, force-pushed main + tags; only `ch1-4@example.invalid` "
        "placeholders remain, guarded by `scripts/test_no_committed_pii.py`). What "
        "remains and cannot be fixed from here: GitHub still serves the OLD commit "
        "objects by direct SHA, so a purge needs GitHub support / GC. Tracked as an "
        "owner action, not a repo defect.",
        "",
        "_This report is a claim about the repo; the live API is the final word._",
    ]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))

    if hard:
        print("\nFAIL: " + "; ".join(hard))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
